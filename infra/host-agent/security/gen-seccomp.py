#!/usr/bin/env python3
"""Generate security/seccomp.json — INTERIM allowlist (§3a.10).

MECHANISM: allowlist (defaultAction ERRNO), so a syscall that is not listed — including
every syscall added to the kernel after the header this was generated from — is denied.
CONTENT: every x86_64 syscall in <asm/unistd_64.h> MINUS the S1 denylist (nested user
namespaces, every mount API, setns, bpf, perf, keyctl, module/kexec/time/swap/reboot …),
with clone/unshare allowed only WITHOUT CLONE_NEWUSER and clone3 -> ENOSYS so libc falls
back to the filterable clone. This is NOT yet Docker's/containers-common's curated
default set: tightening the content to that set (and re-running the desktop boot test)
is an open item. usage: gen-seccomp.py [unistd_64.h] > seccomp.json
"""
import json, re, sys
hdr = sys.argv[1] if len(sys.argv) > 1 else "/usr/include/x86_64-linux-gnu/asm/unistd_64.h"
names = sorted(set(re.findall(r"#define __NR_(\w+)\s+\d+", open(hdr).read())))
DENY = {"mount", "umount2", "pivot_root", "move_mount", "open_tree", "fsopen", "fsconfig", "fsmount", "fspick",
        "mount_setattr", "setns", "keyctl", "add_key", "request_key", "bpf", "perf_event_open", "userfaultfd",
        "kexec_load", "kexec_file_load", "init_module", "finit_module", "delete_module", "create_module",
        "open_by_handle_at", "reboot", "swapon", "swapoff", "acct", "settimeofday", "clock_settime",
        "clock_adjtime", "adjtimex", "iopl", "ioperm", "quotactl", "quotactl_fd", "lookup_dcookie", "syslog",
        "vhangup", "nfsservctl", "get_kernel_syms", "query_module", "uselib", "_sysctl", "afs_syscall",
        "tuxcall", "security", "vserver", "putpmsg", "getpmsg", "lsm_set_self_attr", "fanotify_init",
        "name_to_handle_at", "process_vm_writev", "kcmp"}
SPECIAL = {"clone", "clone3", "unshare"}
NEWUSER = 0x10000000
allow = [n for n in names if n not in DENY and n not in SPECIAL]
prof = {
    "_comment": "GENERATED by gen-seccomp.py — INTERIM allowlist: default deny; content = all x86_64 syscalls "
                "from the build headers minus the S1 denylist. See gen-seccomp.py docstring.",
    "defaultAction": "SCMP_ACT_ERRNO", "defaultErrnoRet": 1,
    "architectures": ["SCMP_ARCH_X86_64", "SCMP_ARCH_X86", "SCMP_ARCH_X32"],
    "syscalls": [
        {"names": allow, "action": "SCMP_ACT_ALLOW"},
        {"names": ["clone", "unshare"], "action": "SCMP_ACT_ALLOW",
         "args": [{"index": 0, "value": NEWUSER, "valueTwo": 0, "op": "SCMP_CMP_MASKED_EQ"}]},
        {"names": ["clone3"], "action": "SCMP_ACT_ERRNO", "errnoRet": 38},
    ]}
json.dump(prof, sys.stdout, indent=1)
print()
