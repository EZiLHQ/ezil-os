// Keep the browser payload inside extension.js: the offline VSIX packager ships that bundle only.
import { createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';

const sources = ['contract.ts', 'messages.ts', 'state.ts', 'webview.ts'];
const hash = createHash('sha256');
for (const file of sources) hash.update(await readFile(new URL(file, import.meta.url)));
const result = await Bun.build({ entrypoints: [new URL('webview.ts', import.meta.url).pathname], target: 'browser' });
if (!result.success) throw new Error('Could not build preview browser script');
const script = await result.outputs[0]!.text();
await Bun.write(new URL('script.generated.ts', import.meta.url),
    `// Generated by build-script.ts; committed for the offline VSIX packager.\nexport const previewSourceHash = ${JSON.stringify(hash.digest('hex'))};\nexport const previewScript = ${JSON.stringify(script)};\n`);
