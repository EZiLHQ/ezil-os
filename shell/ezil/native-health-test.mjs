import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const source = readFileSync(new URL('./native-runtime.js', import.meta.url), 'utf8');
const { watchNativeSurface } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const scheduled = new Map(); let id = 0, checks = 0, failures = 0, ready = true;
const timers = { schedule(fn, delay) { assert.equal(delay, 2000); scheduled.set(++id, fn); return id; }, cancel(id) { scheduled.delete(id); } };
const fire = async () => { const [id, fn] = scheduled.entries().next().value; scheduled.delete(id); await fn(); };
let stop = watchNativeSurface({ confirm: async () => { checks++; return ready; } }, () => failures++, timers);
await fire(); assert.equal(checks, 1); assert.equal(scheduled.size, 1); assert.equal(failures, 0);
ready = false; await fire(); assert.equal(failures, 1); assert.equal(scheduled.size, 0); stop();
let finish;
stop = watchNativeSurface({ confirm: () => new Promise(resolve => { finish = resolve; }) }, () => failures++, timers);
const pending = fire(); assert.equal(scheduled.size, 0, 'no overlap while confirming'); stop(); finish(false); await pending;
assert.equal(failures, 1, 'disposed surface ignores stale result'); assert.equal(scheduled.size, 0);
stop = watchNativeSurface({ confirm: async () => { throw Error('unreachable'); } }, () => failures++, timers);
await fire(); assert.equal(failures, 2); assert.equal(scheduled.size, 0); stop();
watchNativeSurface(null, () => assert.fail('Hosted surfaces must not be monitored'), timers)();
assert.equal(scheduled.size, 0);
console.log('PASS native health monitoring: success, failure, disposal, no overlapping probes, exceptions and hosted isolation');
